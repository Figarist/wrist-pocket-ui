#!/usr/bin/env node
// Builds the derived files from the hand-written sources:
//   wrist-pocket-ui.css  - single-file bundle (tokens + base + components + header)
//   scss/_tokens.scss    - Sass variables and a CSS-variables mixin for Sass sites
// Usage: node scripts/build.mjs [--check]
// --check writes nothing and exits 1 when a derived file is stale.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCES = ['tokens.css', 'base.css', 'components.css', 'header.css'];

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
const version = JSON.parse(read('package.json')).version;

/** Returns [name, value] pairs of the custom properties declared in tokens.css :root. */
export function parseTokens(css = read('tokens.css')) {
  const root = css.match(/:root\s*\{([\s\S]*?)\n\}/);
  if (!root) throw new Error('tokens.css has no :root block');
  const body = root[1].replace(/\/\*[\s\S]*?\*\//g, '');
  return [...body.matchAll(/(--wp-[a-z0-9-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]);
}

export function buildBundle() {
  const banner = `/*! Wrist & Pocket UI v${version} | MIT | https://github.com/Figarist/wrist-pocket-ui */\n` +
    '/* Generated by scripts/build.mjs from ' + SOURCES.join(', ') + '. Do not edit. */\n';
  return banner + SOURCES.map((f) => `\n/* ---- ${f} ---- */\n` + read(f).trim() + '\n').join('');
}

export function buildScss() {
  const tokens = parseTokens();
  const lines = [
    `// Wrist & Pocket UI v${version} - design tokens for Sass.`,
    '// Generated by scripts/build.mjs from tokens.css. Do not edit.',
    '// Usage: @use "tokens" as *;  (or the name you vendored it under), then $wp-accent or @include wp-css-variables;',
    '',
    ...tokens.map(([name, value]) => `$${name.slice(2)}: ${value};`),
    '',
    '// Emits every token as a CSS custom property (put it inside :root).',
    '@mixin wp-css-variables {',
    // Literal values (not #{$var}) so quoted font names keep their quotes.
    ...tokens.map(([name, value]) => `  ${name}: ${value};`),
    '}',
    '',
  ];
  return lines.join('\n');
}

export const OUTPUTS = {
  'wrist-pocket-ui.css': buildBundle,
  'scss/_tokens.scss': buildScss,
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, build] of Object.entries(OUTPUTS)) {
    const next = build();
    let current = null;
    try { current = read(rel); } catch { /* missing */ }
    if (current === next) continue;
    if (check) { console.error(`stale: ${rel} (run node scripts/build.mjs)`); stale++; continue; }
    mkdirSync(dirname(join(ROOT, rel)), { recursive: true });
    writeFileSync(join(ROOT, rel), next);
    console.log(`wrote ${rel}`);
  }
  if (stale) process.exit(1);
  if (check) console.log('derived files are up to date');
}
